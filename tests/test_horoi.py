HERE = Path(__file__).resolve().parent
EXAMPLE = HERE / "example.ttl"          # the Decision ontology, do, as a real case

# A second ontology, with another namespace and prefix and no vann header,
# so that nothing in horoi can lean on do.
SMALL = """@prefix owl: <http://www.w3.org/2002/07/owl#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix ex: <https://example.org/pets#> .
<https://example.org/pets> a owl:Ontology ; owl:versionInfo "1.0.0" ; rdfs:label "Pets" .
ex:Pet a owl:Class ; rdfs:label "Pet" ; rdfs:comment "An animal kept for company." .
ex:Owner a owl:Class ; rdfs:label "Owner" ; rdfs:comment "Whoever keeps a pet." .
ex:keptBy a owl:ObjectProperty ; rdfs:label "kept by" ; rdfs:domain ex:Pet ; rdfs:comment "Relates a pet to its keeper." .
ex:name a owl:DatatypeProperty ; rdfs:label "name" ; rdfs:domain ex:Pet ; rdfs:comment "Relates a pet to what it is called." .
"""
ODD = SMALL + "ex:Toy a owl:Class ; rdfs:subClassOf ex:Owner .\n"     # a shape the diagram has no slot for


def graph(text=None, path=None):
    g = Graph()
    g.parse(data=text, format="turtle") if text else g.parse(path, format="turtle")
    return g


class Build(unittest.TestCase):
    def test_writes_every_file(self):
        with tempfile.TemporaryDirectory() as out:
            latest, _ = build(EXAMPLE, out, example=HERE / "example-data.ttl")
            self.assertEqual(latest, "0.2.0")
            for name in ("index.html", "example.svg", "example.ttl", "example.rdf", "example.jsonld", "example.nt"):
                self.assertTrue((Path(out) / name).exists(), name)
            self.assertTrue((Path(out) / "0.2.0" / "example.ttl").exists())

    def test_page_has_a_card_per_term_and_credits_horoi(self):
        with tempfile.TemporaryDirectory() as out:
            build(EXAMPLE, out)
            html = (Path(out) / "index.html").read_text(encoding="utf-8")
        for term in ("Decision", "Option", "Context", "hasPremise", "chooses", "inContext"):
            self.assertIn(f'id="{term}"', html)
        self.assertIn('generated by <a href="https://github.com/kvistgaard/horoi">horoi</a>', html)
        self.assertNotIn('id="example"', html)       # no example given, no example section

    def test_another_ontology_uses_its_own_prefix(self):
        with tempfile.TemporaryDirectory() as tmp:
            src = Path(tmp) / "pets.ttl"
            src.write_text(SMALL, encoding="utf-8")
            build(src, Path(tmp) / "dist")
            html = (Path(tmp) / "dist" / "index.html").read_text(encoding="utf-8")
            self.assertTrue((Path(tmp) / "dist" / "pets.svg").exists())
        self.assertIn('<span class="mark">pets</span>', html)
        self.assertIn(">pets:Owner<", html.replace("</a>", "<"))
        self.assertNotIn("do:", html)

    def test_an_undrawable_ontology_is_published_without_a_diagram(self):
        said = io.StringIO()
        with tempfile.TemporaryDirectory() as tmp:
            src = Path(tmp) / "pets.ttl"
            src.write_text(ODD, encoding="utf-8")
            with mock.patch.dict(os.environ, {"GITHUB_ACTIONS": ""}), contextlib.redirect_stderr(said):
                build(src, Path(tmp) / "dist")
            html = (Path(tmp) / "dist" / "index.html").read_text(encoding="utf-8")
            self.assertFalse((Path(tmp) / "dist" / "pets.svg").exists())
        self.assertIn('id="Toy"', html)
        self.assertNotIn('id="diagram"', html)
        self.assertNotIn('href="#diagram"', html)
        self.assertIn("the page of pets 1.0.0 has no diagram", said.getvalue())

    def test_a_release_that_cant_be_drawn_does_not_stop_the_build(self):
        said = io.StringIO()
        with tempfile.TemporaryDirectory() as tmp:
            repo, src = Path(tmp), Path(tmp) / "pets.ttl"

            def git(*args):
                subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@example.org", *args],
                               cwd=repo, check=True, capture_output=True)
            git("init", "-q")
            src.write_text(ODD, encoding="utf-8")
            git("add", "pets.ttl")
            git("commit", "-q", "-m", "1.0.0")
            git("tag", "v1.0.0")
            src.write_text(SMALL.replace('"1.0.0"', '"1.1.0"'), encoding="utf-8")
            with mock.patch.dict(os.environ, {"GITHUB_ACTIONS": ""}), contextlib.redirect_stderr(said):
                latest, built = build(src, repo / "dist", all_tags=True)
            self.assertEqual((latest, built), ("1.1.0", ["1.0.0"]))
            self.assertIn('id="diagram"', (repo / "dist" / "index.html").read_text(encoding="utf-8"))
            self.assertNotIn('id="diagram"', (repo / "dist" / "1.0.0" / "index.html").read_text(encoding="utf-8"))
        self.assertIn("the page of pets 1.0.0 has no diagram", said.getvalue())

    def test_on_github_a_warning_shows_on_the_run(self):
        said = io.StringIO()
        with mock.patch.dict(os.environ, {"GITHUB_ACTIONS": "true"}), contextlib.redirect_stdout(said):
            warn("no diagram")
        self.assertEqual(said.getvalue(), "::warning::horoi: no diagram\n")

    def test_sidebar_lists_labels_with_their_curie_on_hover(self):
        with tempfile.TemporaryDirectory() as tmp:
            src = Path(tmp) / "pets.ttl"
            src.write_text(SMALL, encoding="utf-8")
            build(src, Path(tmp) / "dist")
            html = (Path(tmp) / "dist" / "index.html").read_text(encoding="utf-8")
        aside = re.search(r"<aside>(.*?)</aside>", html, re.S).group(1)
        self.assertIn('<a href="#keptBy" title="pets:keptBy">kept by</a>', aside)
        self.assertIn('<a href="#Owner" title="pets:Owner">Owner</a>', aside)

    def test_sidebar_folds_and_its_button_stays_out(self):
        with tempfile.TemporaryDirectory() as out:
            build(EXAMPLE, out)
            html = (Path(out) / "index.html").read_text(encoding="utf-8")
        aside = re.search(r"<aside>(.*?)</aside>", html, re.S).group(1)
        button = re.search(r'<button id="side"[^>]*>', aside).group(0)
        self.assertIn('aria-expanded="true"', button)
        self.assertIn('aria-keyshortcuts="Control+["', button)
        panel ='id="%s"' % re.search(r'aria-controls="([^"]+)"', button).group(1)
        self.assertIn(panel, aside)
        self.assertLess(aside.index(button), aside.index(panel))    # the button stays when the panel folds
        self.assertIn('id="q"', aside[aside.index(panel):])

    def test_the_shortcut_on_hover_stays_legible(self):
        with tempfile.TemporaryDirectory() as out:
            build(EXAMPLE, out)
            html = (Path(out) / "index.html").read_text(encoding="utf-8")
        self.assertIn("Ctrl + [", html)
        self.assertNotIn("[)", html)                    # a closing bracket beside it reads as one symbol

    def test_section_titles_just_reach_the_contrast_guideline(self):
        def luminance(colour):
            def channel(i):
                c = int(colour[i:i + 2], 16) / 255
                return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
            return 0.2126 * channel(1) + 0.7152 * channel(3) + 0.0722 * channel(5)

        def ratio(css):
            pair = sorted((luminance(re.search(rf"--{name}:(#\w+)", css).group(1)) for name in ("bg", "section")), reverse=True)
            return (pair[0] + 0.05) / (pair[1] + 0.05)
        with tempfile.TemporaryDirectory() as out:
            build(EXAMPLE, out)
            html = (Path(out) / "index.html").read_text(encoding="utf-8")
        for theme in (html, DARK_CSS):
            self.assertGreaterEqual(ratio(theme), 4.5)
            self.assertLess(ratio(theme), 4.6)          # enough to comply, not more

    def test_a_folded_sidebar_is_restored_before_the_page_paints(self):
        with tempfile.TemporaryDirectory() as out:
            build(EXAMPLE, out)
            html = (Path(out) / "index.html").read_text(encoding="utf-8")
        self.assertIn("localStorage.getItem('horoi-sidebar')", html[:html.index("</head>")])

    def test_header_and_sidebar_share_their_left_edge(self):
        with tempfile.TemporaryDirectory() as out:
            build(EXAMPLE, out)
            html = (Path(out) / "index.html").read_text(encoding="utf-8")
        self.assertRegex(html, r"\.top \{[^}]*padding:12px var\(--gutter\)")
        self.assertRegex(html, r"aside \{[^}]*margin-left:var\(--gutter\)")
        self.assertRegex(html, r"\.wrap \{[^}]*padding:36px 0 80px")    # nothing else offsets the sidebar

    def test_every_place_on_the_page_follows_the_list_of_groups(self):
        pets = "https://example.org/pets#"

        class Shapes(Page):                             # the shape of a later SHACL reader
            def groups(self):
                facts = lambda t: ("shape", [])
                terms = [URIRef(pets + n) for n in ("Pet", "Owner", "keptBy")]
                return [Group("node shape", "node shapes", terms[:2], facts),
                        Group("property shape", "property shapes", [], facts),
                        Group("rule", "rules", terms[2:], facts)]
        html = Shapes(graph(SMALL)).render('<svg class="hr-diagram"></svg>', "pets")
        aside = re.search(r"<aside>(.*?)</aside>", html, re.S).group(1)
        self.assertEqual(re.findall(r'<p class="navh">([^<]+)</p>', aside), ["Node shapes", "Rules"])
        self.assertIn('<a href="#node-shapes">Node shapes</a><a href="#rules">Rules</a>', html)
        self.assertIn('<section id="node-shapes"><h2>Node shapes</h2>', html)
        self.assertIn('<section id="rules"><h2>Rules</h2>', html)
        self.assertIn("2 node shapes and 1 rule, drawn from", html)
        self.assertNotIn("property shapes", html.lower())   # a group with no terms doesn't appear
        for fixed in ("Classes", "Properties"):
            self.assertNotIn(fixed, html)

    def test_an_ontology_keeps_its_existing_anchors(self):
        with tempfile.TemporaryDirectory() as out:
            build(EXAMPLE, out)
            html = (Path(out) / "index.html").read_text(encoding="utf-8")
        self.assertIn('<section id="classes"><h2>Classes</h2>', html)
        self.assertIn('<section id="properties"><h2>Properties</h2>', html)


class Diagram(unittest.TestCase):
    def test_every_term_has_its_curie_on_hover(self):
        svg = draw(graph(path=EXAMPLE))
        titles = set(re.findall(r"<title>([^<]+)</title>", svg))
        for t in ("do:Decision", "do:Option", "do:Context", "do:hasPremise", "do:chooses ⊑ do:hasOption"):
            self.assertIn(t, titles)

    def test_names_are_labels(self):
        svg = draw(graph(path=EXAMPLE))
        self.assertIn(">has premise<", svg)
        self.assertNotIn(">hasPremise<", svg)

    def test_a_class_no_property_reaches_still_appears(self):
        svg = draw(graph(SMALL))
        self.assertIn("<title>pets:Owner</title>", svg)

    def test_an_unsupported_shape_is_not_drawn(self):
        with self.assertRaises(Undrawable):
            draw(graph(ODD))
        with self.assertRaises(Undrawable):
            draw(graph(SMALL.split("ex:Pet a")[0]))      # no class at all

    def test_the_diagram_command_stops_on_an_unsupported_shape(self):
        with tempfile.TemporaryDirectory() as tmp:
            src = Path(tmp) / "pets.ttl"
            src.write_text(ODD, encoding="utf-8")
            with self.assertRaises(SystemExit) as e:
                main(["diagram", str(src)])
            self.assertTrue(str(e.exception.code).startswith("horoi: "))
            self.assertFalse((Path(tmp) / "pets.svg").exists())

    def test_superclasses_sit_above_and_self_loops_stack_on_the_right(self):
        svg = draw(graph(path=EXAMPLE))

        def box(curie):
            m = re.search(rf'<title>{re.escape(curie)}</title><rect class="c" x="(-?\d+)" y="(-?\d+)" '
                          r'width="(\d+)" height="(\d+)"', svg)
            return tuple(map(int, m.groups()))
        communication, decision, option = box("do:Communication"), box("do:Decision"), box("do:Option")
        self.assertLess(communication[1] + communication[3], decision[1])
        self.assertLess(decision[1] + decision[3], option[1])
        rows = set()
        for name in ("revises", "triggered by", "has unconfirmed premise"):
            x, y = map(float, re.search(rf'x="([\d.]+)" y="([\d.]+)" text-anchor="start">{name}<', svg).groups())
            self.assertGreater(x, decision[0] + decision[2])
            rows.add(y)
        self.assertEqual(len(rows), 3)                  # each name on a row of its own

    def test_a_class_from_another_vocabulary_shows_its_curie(self):
        svg = draw(graph(path=EXAMPLE))
        self.assertIn("<title>foaf:Agent</title>", svg)
        self.assertIn(">foaf:Agent<", svg)

    def test_properties_with_no_domain_start_from_any_resource_under_the_spine(self):
        extra = ('ex:owns a owl:ObjectProperty ; rdfs:label "owns" ; rdfs:range ex:Owner .\n'
                 'ex:note a owl:DatatypeProperty ; rdfs:label "note" .\n'
                 'ex:seeAlso a owl:ObjectProperty ; rdfs:label "see also" .\n')
        svg = draw(graph(SMALL + extra))
        node = re.search(r'<title>No domain declared\.</title><rect class="a" x="(-?\d+)" y="(-?\d+)"', svg)
        pet = re.search(r'<title>pets:Pet</title><rect class="c" x="(-?\d+)" y="(-?\d+)" width="\d+" height="(\d+)"', svg)
        self.assertIsNotNone(node)
        self.assertEqual(node[1], pet[1])                                   # in the column
        self.assertGreater(int(node[2]), int(pet[2]) + int(pet[3]))         # under the spine
        for t in ("pets:owns", "pets:note", "pets:seeAlso", "pets:Owner"):
            self.assertIn(f"<title>{t}</title>", svg)

    def test_a_class_two_neighbouring_rows_reach_is_drawn_once_with_its_self_loops(self):
        extra = ('ex:Owner rdfs:label "Owner" .\n'
                 'ex:keptBy rdfs:range ex:Owner .\n'
                 'ex:owns a owl:ObjectProperty ; rdfs:label "owns" ; rdfs:range ex:Owner .\n'
                 'ex:knows a owl:ObjectProperty ; rdfs:label "knows" ; rdfs:domain ex:Owner ; rdfs:range ex:Owner .\n')
        svg = draw(graph(SMALL + extra))
        self.assertEqual(svg.count("<title>pets:Owner</title>"), 1)
        owner = re.search(r'<title>pets:Owner</title><rect class="c" x="(-?\d+)" y="(-?\d+)" width="(\d+)" height="(\d+)"', svg)
        x, y, w, h = map(int, owner.groups())
        lx, ly = map(float, re.search(r'x="([\d.]+)" y="([\d.]+)" text-anchor="start">knows<', svg).groups())
        self.assertGreater(lx, x + w)                                       # on its right edge
        self.assertTrue(y < ly < y + h)

    def test_a_class_rows_apart_reach_is_not_drawn(self):
        extra = ('ex:Kitten a owl:Class ; rdfs:subClassOf ex:Pet .\n'
                 'ex:Breeder a owl:Class .\n'
                 'ex:breeds a owl:ObjectProperty ; rdfs:range ex:Breeder .\n'
                 'ex:soldBy a owl:ObjectProperty ; rdfs:domain ex:Pet ; rdfs:range ex:Breeder .\n')
        with self.assertRaises(Undrawable):         # Pet, then Kitten, then any resource
            draw(graph(SMALL + extra))


