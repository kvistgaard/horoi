"""Tests for horoi.

    python -m unittest discover tests
"""
import re
import tempfile
import unittest
from pathlib import Path

from rdflib import Graph

from horoi.build import build
from horoi.cli import main
from horoi.diagram import draw

HERE = Path(__file__).resolve().parent
EXAMPLE = HERE / "example.ttl"          # the Decision ontology, do, as a real case

# A second ontology, with another namespace and prefix and no vann header,
# so that nothing in horoi can lean on do.
SMALL = """@prefix owl: <http://www.w3.org/2002/07/owl#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix ex: <https://example.org/pets#> .
<https://example.org/pets> a owl:Ontology ; owl:versionInfo "1.0.0" ; rdfs:label "Pets" .
ex:Pet a owl:Class ; rdfs:label "Pet" ; rdfs:comment "An animal kept for company." .
ex:Owner a owl:Class ; rdfs:label "Owner" ; rdfs:comment "Whoever keeps a pet." .
ex:keptBy a owl:ObjectProperty ; rdfs:label "kept by" ; rdfs:domain ex:Pet ; rdfs:comment "Relates a pet to its keeper." .
ex:name a owl:DatatypeProperty ; rdfs:label "name" ; rdfs:domain ex:Pet ; rdfs:comment "Relates a pet to what it is called." .
"""


def graph(text=None, path=None):
    g = Graph()
    g.parse(data=text, format="turtle") if text else g.parse(path, format="turtle")
    return g


class Build(unittest.TestCase):
    def test_writes_every_file(self):
        with tempfile.TemporaryDirectory() as out:
            latest, _ = build(EXAMPLE, out, example=HERE / "example-data.ttl")
            self.assertEqual(latest, "0.2.0")
            for name in ("index.html", "example.svg", "example.ttl", "example.rdf", "example.jsonld", "example.nt"):
                self.assertTrue((Path(out) / name).exists(), name)
            self.assertTrue((Path(out) / "0.2.0" / "example.ttl").exists())

    def test_page_has_a_card_per_term_and_credits_horoi_only_when_asked(self):
        with tempfile.TemporaryDirectory() as out:
            build(EXAMPLE, out)
            html = (Path(out) / "index.html").read_text(encoding="utf-8")
            build(EXAMPLE, out, credit=True)
            credited = (Path(out) / "index.html").read_text(encoding="utf-8")
        for term in ("Decision", "Option", "Context", "hasPremise", "chooses", "inContext"):
            self.assertIn(f'id="{term}"', html)
        self.assertNotIn("generated by", html)
        self.assertIn('generated by <a href="https://github.com/kvistgaard/horoi">horoi</a>', credited)
        self.assertNotIn('id="example"', html)       # no example given, no example section

    def test_another_ontology_uses_its_own_prefix(self):
        with tempfile.TemporaryDirectory() as tmp:
            src = Path(tmp) / "pets.ttl"
            src.write_text(SMALL, encoding="utf-8")
            build(src, Path(tmp) / "dist")
            html = (Path(tmp) / "dist" / "index.html").read_text(encoding="utf-8")
            self.assertTrue((Path(tmp) / "dist" / "pets.svg").exists())
        self.assertIn('<span class="mark">pets</span>', html)
        self.assertIn(">pets:Owner<", html.replace("</a>", "<"))
        self.assertNotIn("do:", html)


class Diagram(unittest.TestCase):
    def test_every_term_has_its_curie_on_hover(self):
        svg = draw(graph(path=EXAMPLE))
        titles = set(re.findall(r"<title>([^<]+)</title>", svg))
        for t in ("do:Decision", "do:Option", "do:Context", "do:hasPremise", "do:chooses ⊑ do:hasOption"):
            self.assertIn(t, titles)

    def test_names_are_labels(self):
        svg = draw(graph(path=EXAMPLE))
        self.assertIn(">has premise<", svg)
        self.assertNotIn(">hasPremise<", svg)

    def test_check_fails_on_a_stale_drawing(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "do.svg"
            self.assertEqual(main(["diagram", str(EXAMPLE), "--out", str(out)]), 0)
            self.assertEqual(main(["diagram", str(EXAMPLE), "--out", str(out), "--check"]), 0)
            out.write_text(out.read_text(encoding="utf-8").replace("has premise", "has premiss"), encoding="utf-8")
            self.assertEqual(main(["diagram", str(EXAMPLE), "--out", str(out), "--check"]), 1)

    def test_a_class_no_property_reaches_still_appears(self):
        svg = draw(graph(SMALL))
        self.assertIn("<title>pets:Owner</title>", svg)

    def test_an_unsupported_shape_stops_with_a_message(self):
        odd = SMALL + "ex:Toy a owl:Class ; rdfs:subClassOf ex:Owner .\n"
        with self.assertRaises(SystemExit) as e:
            draw(graph(odd))
        self.assertIn("horoi:", str(e.exception.code))

    def test_superclasses_sit_above_and_self_loops_stack_on_the_right(self):
        svg = draw(graph(path=EXAMPLE))

        def box(curie):
            m = re.search(rf'<title>{re.escape(curie)}</title><rect class="c" x="(-?\d+)" y="(-?\d+)" '
                          r'width="(\d+)" height="(\d+)"', svg)
            return tuple(map(int, m.groups()))
        communication, decision, option = box("do:Communication"), box("do:Decision"), box("do:Option")
        self.assertLess(communication[1] + communication[3], decision[1])
        self.assertLess(decision[1] + decision[3], option[1])
        rows = set()
        for name in ("revises", "triggered by", "has unconfirmed premise"):
            x, y = map(float, re.search(rf'x="([\d.]+)" y="([\d.]+)" text-anchor="start">{name}<', svg).groups())
            self.assertGreater(x, decision[0] + decision[2])
            rows.add(y)
        self.assertEqual(len(rows), 3)                  # each name on a row of its own

    def test_a_class_from_another_vocabulary_shows_its_curie(self):
        svg = draw(graph(path=EXAMPLE))
        self.assertIn("<title>foaf:Agent</title>", svg)
        self.assertIn(">foaf:Agent<", svg)

    def test_a_property_from_any_resource_reaches_a_class_above(self):
        owns = 'ex:owns a owl:ObjectProperty ; rdfs:label "owns" ; rdfs:range ex:Owner .\n'
        svg = draw(graph(SMALL + owns))
        self.assertIn("<title>pets:owns</title>", svg)
        self.assertIn("<title>pets:Owner</title>", svg)


if __name__ == "__main__":
    unittest.main()
